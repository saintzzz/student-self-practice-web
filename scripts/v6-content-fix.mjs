#!/usr/bin/env node
/**
 * CR-51 ops script - fixes V6 content defects in practice.qb_questions.
 *
 * Usage:
 *   node scripts/v6-content-fix.mjs passage            # backfill `passage` from source JSONL
 *   node scripts/v6-content-fix.mjs explain --dry      # LLM-rewrite lazy explanations (preview)
 *   node scripts/v6-content-fix.mjs explain [--limit N]
 *
 * Env:
 *   SUPABASE_SERVICE_KEY - else read from ~/.config/devin/secrets/supabase_new_keys.json
 *   GEMINI_API_KEY       - required for `explain` (provider-agnostic override: AI_MODEL)
 */
import { readFileSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const SOURCE_JSONL = join(homedir(), 'Desktop/primary-question-bank-v6-final/data/questions-v6.jsonl');
const SUPA_URL = 'https://cxjpgfhqchjoernfmcra.supabase.co';

function serviceKey() {
  if (process.env.SUPABASE_SERVICE_KEY) return process.env.SUPABASE_SERVICE_KEY;
  const p = join(homedir(), '.config/devin/secrets/supabase_new_keys.json');
  return JSON.parse(readFileSync(p, 'utf8')).keys.service_role;
}

const KEY = serviceKey();
const HEADERS = {
  apikey: KEY,
  Authorization: `Bearer ${KEY}`,
  'Accept-Profile': 'practice',
  'Content-Profile': 'practice',
  'Content-Type': 'application/json',
};

async function patchQuestion(id, fields) {
  const res = await fetch(`${SUPA_URL}/rest/v1/qb_questions?id=eq.${encodeURIComponent(id)}`, {
    method: 'PATCH',
    headers: { ...HEADERS, Prefer: 'return=minimal' },
    body: JSON.stringify(fields),
  });
  if (!res.ok) throw new Error(`PATCH ${id}: ${res.status} ${await res.text()}`);
}

/* ---------------- passage backfill ---------------- */

async function backfillPassage() {
  if (!existsSync(SOURCE_JSONL)) throw new Error(`missing ${SOURCE_JSONL}`);
  const rows = readFileSync(SOURCE_JSONL, 'utf8')
    .split('\n')
    .filter(Boolean)
    .map((l) => JSON.parse(l))
    .filter((d) => d.passage)
    .map((d) => ({ id: d.id, passage: d.passage }));
  console.log(`source rows with passage: ${rows.length}`);

  let done = 0, failed = 0;
  const CHUNK = 12;
  for (let i = 0; i < rows.length; i += CHUNK) {
    await Promise.all(
      rows.slice(i, i + CHUNK).map(async (r) => {
        try {
          await patchQuestion(r.id, { passage: r.passage });
          done++;
        } catch (e) {
          failed++;
          console.error(String(e).slice(0, 200));
        }
      }),
    );
    process.stdout.write(`\r${done}/${rows.length}`);
  }
  console.log(`\npassage backfill done=${done} failed=${failed}`);
}

/* ---------------- explanation rewrite ---------------- */

// Lazy/template explanation prefixes generated by build_v6.py.
const LAZY = [
  /^Đáp án phù hợp với ngữ cảnh/,
  /^Chọn câu trả lời phù hợp/,
  /^Chọn câu phù hợp nhất/,
  /^Thông tin phù hợp với kiến thức/,
  /^Thông tin này xuất hiện trong đoạn đọc\.?$/,
  /^Câu đúng được nêu trực tiếp trong đoạn đọc\.?$/,
  /^Nội dung nghe trùng với câu trả lời đúng\.?$/,
  /^Nghe và chọn đúng câu được đọc\.?$/,
  /^Nghe câu trả lời và chọn nội dung phù hợp\.?$/,
  /^Sắp xếp (các )?từ để tạo thành câu/,
  /^Quan sát sơ đồ và dùng kiến thức/,
  /^Câu nói mở; giáo viên/,
  /^Có nhiều đáp án đúng/,
];

const isLazy = (s) => typeof s === 'string' && LAZY.some((re) => re.test(s.trim()));

async function fetchLazyRows() {
  const out = [];
  const PAGE = 1000;
  for (let off = 0; ; off += PAGE) {
    const res = await fetch(
      `${SUPA_URL}/rest/v1/qb_questions?select=id,grade,subject,question_type,prompt_text,transcript,passage,choices,answer,explanation_vi&offset=${off}&limit=${PAGE}`,
      { headers: HEADERS },
    );
    if (!res.ok) throw new Error(`fetch page: ${res.status} ${await res.text()}`);
    const page = await res.json();
    out.push(...page.filter((r) => isLazy(r.explanation_vi)));
    if (page.length < PAGE) break;
  }
  return out;
}

function answerText(q) {
  const a = q.answer ?? {};
  if (a.text) return String(a.text);
  if (a.boolean !== undefined) return a.boolean ? 'True' : 'False';
  if (a.index !== undefined && Array.isArray(q.choices)) {
    const c = q.choices[a.index];
    return typeof c === 'string' ? c : JSON.stringify(c);
  }
  return '';
}

function geminiPrompt(batch) {
  const items = batch.map((q) => ({
    id: q.id,
    grade: q.grade,
    type: q.question_type,
    prompt: q.prompt_text,
    passage: q.passage || undefined,
    transcript: q.transcript || undefined,
    choices: q.choices || undefined,
    correct_answer: answerText(q),
  }));
  return `Bạn là giáo viên tiếng Anh tiểu học Việt Nam. Với mỗi câu hỏi dưới đây, viết lời giải thích NGẮN (1-2 câu) bằng tiếng Việt đơn giản cho học sinh lớp đã nêu.

Yêu cầu:
- Giải thích TẠI SAO đáp án đúng (quy tắc ngữ pháp, nghĩa của từ, hoặc bằng chứng trong đoạn đọc/hội thoại nghe).
- Nếu hữu ích, nêu ngắn gọn vì sao đáp án khác sai (ví dụ sai ngữ pháp).
- Với câu đọc hiểu/nghe: trích bằng chứng cụ thể trong passage/transcript.
- Với câu sắp xếp từ: giải thích cấu trúc câu đúng.
- Với câu khoa học: nêu kiến thức khoa học đúng, đơn giản.
- KHÔNG lặp lại nguyên văn "đáp án đúng là X". KHÔNG dùng gạch dài. Không markdown.
- Giọng thân thiện, khuyến khích. Tối đa ~40 từ.

Trả về JSON duy nhất, không text khác: {"<id>": "<explanation>", ...}

Câu hỏi:
${JSON.stringify(items, null, 0)}`;
}

async function callGemini(prompt) {
  const key = process.env.GEMINI_API_KEY;
  if (!key) throw new Error('GEMINI_API_KEY not set');
  const model = process.env.AI_MODEL || 'gemini-2.5-flash';
  const res = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${key}`,
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{ parts: [{ text: prompt }] }],
        generationConfig: {
          responseMimeType: 'application/json',
          temperature: 0.3,
          ...(model.startsWith('gemini-2') ? { thinkingConfig: { thinkingBudget: 0 } } : {}),
        },
      }),
    },
  );
  if (!res.ok) throw new Error(`Gemini ${res.status}: ${(await res.text()).slice(0, 300)}`);
  const data = await res.json();
  const text = data.candidates?.[0]?.content?.parts?.[0]?.text ?? '';
  return JSON.parse(text);
}

async function rewriteExplanations({ dry, limit }) {
  let rows = await fetchLazyRows();
  console.log(`lazy explanations: ${rows.length}`);
  if (limit) rows = rows.slice(0, limit);

  const BATCH = 15;
  let updated = 0, failed = 0;
  for (let i = 0; i < rows.length; i += BATCH) {
    const batch = rows.slice(i, i + BATCH);
    try {
      const map = await callGemini(geminiPrompt(batch));
      for (const q of batch) {
        const text = map[q.id]?.trim();
        if (!text || text.length < 15 || isLazy(text)) {
          failed++;
          console.error(`bad/empty explanation for ${q.id}: ${JSON.stringify(text)}`);
          continue;
        }
        if (dry) {
          console.log(`[dry] ${q.id}\n      old: ${q.explanation_vi}\n      new: ${text}`);
          updated++;
        } else {
          await patchQuestion(q.id, { explanation_vi: text });
          updated++;
        }
      }
    } catch (e) {
      failed += batch.length;
      console.error(`batch ${i / BATCH} failed: ${String(e).slice(0, 300)}`);
      await new Promise((r) => setTimeout(r, 5000));
    }
    process.stdout.write(`\r${Math.min(i + BATCH, rows.length)}/${rows.length} processed`);
    await new Promise((r) => setTimeout(r, 1200));
  }
  console.log(`\nexplain ${dry ? '(dry) ' : ''}updated=${updated} failed=${failed}`);
}

/* ---------------- main ---------------- */

const [cmd, ...flags] = process.argv.slice(2);
const dry = flags.includes('--dry');
const limitIdx = flags.indexOf('--limit');
const limit = limitIdx >= 0 ? Number(flags[limitIdx + 1]) : 0;

if (cmd === 'passage') await backfillPassage();
else if (cmd === 'explain') await rewriteExplanations({ dry, limit });
else {
  console.log('usage: v6-content-fix.mjs passage | explain [--dry] [--limit N]');
  process.exit(1);
}
