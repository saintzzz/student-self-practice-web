/**
 * CR-115 / r144: build src/data/vocabImages.ts from APPROVED attribution
 * records - never from raw concepts/ filenames, so the manifest can never
 * point a word at an unaudited or non-vocab path (ADR-5, AC-4.9).
 *
 *   node scripts/artgen/build-vocab-images.mjs            emit manifest
 *   node scripts/artgen/build-vocab-images.mjs --publish  copy missing
 *     vocab/<wordId>.webp files from concepts/concept-<wordId>-*.webp
 *     first, then emit the manifest
 *
 * Publishing a NEW image therefore = file in public/images/vocab/ +
 * approved record in public/attribution.json (the audit pipeline), then
 * re-run this script.
 */
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const PUBLIC = join(ROOT, 'public');
const VOCAB_DIR = join(PUBLIC, 'images', 'vocab');
const ATTR = join(PUBLIC, 'attribution.json');
const OUT = join(ROOT, 'src', 'data', 'vocabImages.ts');
const publish = process.argv.includes('--publish');

const records = (JSON.parse(readFileSync(ATTR, 'utf8')).images ?? [])
  .filter(
    (r) =>
      r.reviewStatus === 'approved' &&
      typeof r.wordId === 'string' &&
      typeof r.file === 'string' &&
      r.file.startsWith('/images/vocab/'),
  );

if (publish) {
  let copied = 0;
  for (const r of records) {
    const dest = join(PUBLIC, r.file);
    if (existsSync(dest)) continue;
    /* r144 round 2: never guess a source from the word id - an approved
       record approves specific BYTES. Only a record that binds
       sourceFile + sourceSha256 (content-verified at approval time) may
       restore a missing vocab file; anything else needs a human publish. */
    if (!r.sourceFile || !r.sourceSha256) {
      console.warn(`  ${r.wordId}: no bound source - publish manually after re-audit`);
      continue;
    }
    const srcPath = join(PUBLIC, r.sourceFile);
    if (!existsSync(srcPath)) {
      console.warn(`  ${r.wordId}: bound source missing on disk: ${r.sourceFile}`);
      continue;
    }
    const sha = createHash('sha256').update(readFileSync(srcPath)).digest('hex');
    if (sha !== r.sourceSha256) {
      console.warn(`  ${r.wordId}: source bytes differ from approved hash - refusing to publish`);
      continue;
    }
    copyFileSync(srcPath, dest);
    copied++;
  }
  console.log(`published ${copied} missing vocab file(s)`);
}

const entries = records.filter((r) => existsSync(join(PUBLIC, r.file)));
const missing = records.length - entries.length;
if (missing > 0) {
  console.warn(`warning: ${missing} approved record(s) have no file on disk - run with --publish`);
}

const lines = entries
  .sort((a, b) => a.wordId.localeCompare(b.wordId))
  .map((r) => `  ${JSON.stringify(r.wordId)}: ${JSON.stringify(r.file)},`);

const src = `/**
 * AUTO-GENERATED by scripts/artgen/build-vocab-images.mjs - do not edit.
 * CR-115: wordId -> audited vocab art (ADR-5: /images/vocab/ + approved
 * attribution record). vocab enrichment reads this map; a missing key
 * falls back to the emoji visual chain unchanged.
 */
export const VOCAB_IMAGES: Readonly<Record<string, string>> = {
${lines.join('\n')}
};
`;

writeFileSync(OUT, src);
console.log(`wrote ${entries.length} image entries -> ${OUT}`);
