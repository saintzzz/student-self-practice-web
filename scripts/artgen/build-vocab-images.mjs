/**
 * CR-115: build src/data/vocabImages.ts from the audited concept art in
 * public/images/concepts/. Filename convention: concept-<wordId>-<hash>.webp.
 * Run after every accepted art batch: `node scripts/artgen/build-vocab-images.mjs`.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DIR = join(ROOT, 'public', 'images', 'concepts');
const OUT = join(ROOT, 'src', 'data', 'vocabImages.ts');

const entries = new Map();
for (const file of readdirSync(DIR).sort()) {
  const m = /^concept-(.+)-[0-9a-f]{6}\.webp$/.exec(file);
  if (!m) continue;
  const wordId = m[1];
  if (!entries.has(wordId)) entries.set(wordId, `/images/concepts/${file}`);
}

const lines = [...entries].map(
  ([id, path]) => `  ${JSON.stringify(id)}: ${JSON.stringify(path)},`,
);

const src = `/**
 * AUTO-GENERATED by scripts/artgen/build-vocab-images.mjs - do not edit.
 * CR-115: wordId -> audited concept art. vocab enrichment reads this map;
 * a missing key falls back to the emoji visual chain unchanged.
 */
export const VOCAB_IMAGES: Readonly<Record<string, string>> = {
${lines.join('\n')}
};
`;

writeFileSync(OUT, src);
console.log(`wrote ${entries.size} image entries -> ${OUT}`);
